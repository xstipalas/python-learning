a, b = 0b1101, 0b1010

# Операции & (логическое умножение), | (логическое сложение), ^ (исключающее ИЛИ), ~ (логическое отрицание)
print(f'{a:0b} & {b:0b} = {a & b:0b}')
print(f'{a:0b} | {b:0b} = {a | b:0b}')
print(f'{a:0b} ^ {b:0b} = {a ^ b:0b}')
# При использовании XOR дважды получаем исходное число
print(f'{a:0b} ^ {b:0b} ^ {b:0b} = {a ^ b ^ b:0b}')
print(f'~{a:0b} = {~a:0b}')

print(f'\n{a} & {b} = {a & b}')
print(f'{a} | {b} = {a | b}')
print(f'{a} ^ {b} = {a ^ b}')
print(f'{a ^ b} ^ {b} = {a ^ b ^ b}')
print(f'~{a} = {~a}')

# Умножение на 2 ** x - сдвиг влево на x битов, деление на 2 ** x - сдвиг вправо на x битов
print(f'\n{a:0b} * 2 = {a << 1:0b}')
print(f'{a:0b} // 4 = {a >> 2:0b}')

print(f'\n{a} * 2 = {a << 1}')
print(f'{a} // 4 = {a >> 2}')

# Четность числа зависит от младшего бита: если он 0, число четное, если 1 - нечетное
print(f'\n{a} - {"четное" if a & 1 == 0 else "нечетное"}')
print(f'{b} - {"четное" if b & 1 == 0 else "нечетное"}')

# С помощью битовых операций можно хранить несколько булевых значений в одном числе
READ = 1
EDIT = 2
DELETE = 4
CREATE = 8

user1 = 7
user2 = READ | DELETE

# Проверяем права доступа для каждого пользователя
for i, user in enumerate((user1, user2)):
    print(f'\nПользователь {i+1} может читать: {bool(user & READ)}')
    print(f'Пользователь {i+1} может изменять: {bool(user & EDIT)}')
    print(f'Пользователь {i+1} может удалять: {bool(user & DELETE)}')
    print(f'Пользователь {i+1} может создавать: {bool(user & CREATE)}')